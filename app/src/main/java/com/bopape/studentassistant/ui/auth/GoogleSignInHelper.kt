package com.bopape.studentassistant.ui.auth

import android.app.Activity
import android.content.Context
import android.util.Log
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import com.bopape.studentassistant.R
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.tasks.await

/**
 * Single sign-on with Google (Final PoE requirement).
 *
 * Flow: Android Credential Manager shows the Google account picker -> returns a
 * Google ID token -> the token is exchanged for a Firebase credential, so a
 * Google user ends up in the same Firebase Authentication project (and gets the
 * same per-user data in the API) as an email/password user. The app never sees
 * or stores the user's Google password.
 *
 * References:
 *   Android Developers (2026) Authenticate users with Sign in with Google.
 *   https://developer.android.com/identity/sign-in/credential-manager-siwg
 *   Google (2026) Authenticate with Google on Android (Firebase).
 *   https://firebase.google.com/docs/auth/android/google-signin
 */
class GoogleSignInHelper(private val context: Context) {

    sealed class Result {
        data class Success(val user: FirebaseUser) : Result()
        object Cancelled : Result()
        data class Error(val message: String) : Result()
    }

    private val credentialManager = CredentialManager.create(context)
    private val tag = "GoogleSignInHelper"

    /**
     * The OAuth "web client" ID generated by the google-services plugin from
     * google-services.json once Google is enabled as a sign-in provider in the
     * Firebase console. Looked up by name so the project still compiles before that.
     */
    private fun webClientId(): String? {
        val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        return if (id == 0) null else context.getString(id)
    }

    suspend fun signIn(activity: Activity): Result {
        val clientId = webClientId()
        if (clientId == null) {
            Log.e(tag, "default_web_client_id missing - enable Google sign-in in Firebase and re-download google-services.json")
            return Result.Error(context.getString(R.string.error_google_not_configured))
        }

        return try {
            val option = GetSignInWithGoogleOption.Builder(clientId).build()
            val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
            val credential = credentialManager.getCredential(activity, request).credential

            if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                val googleToken = GoogleIdTokenCredential.createFrom(credential.data)
                val firebaseCredential = GoogleAuthProvider.getCredential(googleToken.idToken, null)
                val authResult = FirebaseAuth.getInstance().signInWithCredential(firebaseCredential).await()
                val user = authResult.user ?: return Result.Error(context.getString(R.string.error_generic))
                Log.i(tag, "Google sign-in succeeded for ${user.uid} (new user: ${authResult.additionalUserInfo?.isNewUser})")
                Result.Success(user)
            } else {
                Log.w(tag, "Unexpected credential type: ${credential.type}")
                Result.Error(context.getString(R.string.error_generic))
            }
        } catch (e: GetCredentialCancellationException) {
            Log.d(tag, "User cancelled Google sign-in")
            Result.Cancelled
        } catch (e: GetCredentialException) {
            Log.w(tag, "Credential Manager error", e)
            Result.Error(context.getString(R.string.error_google_failed, e.message ?: e.type))
        } catch (e: Exception) {
            Log.e(tag, "Firebase sign-in with Google failed", e)
            Result.Error(context.getString(R.string.error_google_failed, e.localizedMessage ?: ""))
        }
    }

    /** Clears the remembered Google account so the picker shows again after sign-out. */
    suspend fun clear() {
        try {
            credentialManager.clearCredentialState(ClearCredentialStateRequest())
        } catch (e: Exception) {
            Log.w(tag, "Could not clear credential state", e)
        }
    }
}
